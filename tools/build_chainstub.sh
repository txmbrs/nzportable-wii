#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p build/chainstub
cc=/opt/devkitpro/devkitPPC/bin/powerpc-eabi-gcc
"$cc" -mcpu=750 -meabi -Os -ffreestanding -fno-builtin -fno-stack-protector -fno-pic -msdata=none -nostdlib -Wl,-Ttext=0x93000000,-e,_start tools/chainstub.S tools/chainstub.c -o build/chainstub/stub.elf
/opt/devkitpro/devkitPPC/bin/powerpc-eabi-objcopy -O binary -j .text build/chainstub/stub.elf build/chainstub/stub.bin
python3 - <<'PY'
from pathlib import Path
p=Path('build/chainstub/stub.bin').read_bytes()
assert len(p)<0x10000
Path('source/platform/wii/chainstub_bytes.h').write_text('/* Generated by tools/build_chainstub.sh */\nstatic const unsigned char chainstub_bytes[] = {'+','.join(map(str,p))+'};\n')
PY
